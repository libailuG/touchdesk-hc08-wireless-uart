static int ordinal(int y,int m,int d)
{
    static const int before[]={0,31,59,90,120,151,181,212,243,273,304,334};
    int p=y-1;
    return p*365+p/4-p/100+p/400+before[m-1]+d+(m>2&&y%4==0&&(y%100!=0||y%400==0));
}
