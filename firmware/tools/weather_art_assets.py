"""Encode original and rain-v2 atlases into memory-mapped RGB565+A8 resources."""
from pathlib import Path
import hashlib,json
from PIL import Image
ROOT=Path(__file__).resolve().parents[1];assets=ROOT/'assets/weather-soft3d';raw=ROOT/'assets/resource-data'
base=Image.open(assets/'atlas.png').convert('RGBA');rain=Image.open(assets/'rain-atlas-v2.png').convert('RGBA')
names=['sun','moon','partly-day','partly-night','cloud','fog','drizzle','rain','heavy-rain','thunder','snow','unknown','moderate-rain','showers-day','freezing-rain','showers-night']
# Keep original public indices; append newly distinct conditions.
new_cells={6:0,7:1,12:2,8:3,13:4,15:5,14:6,9:7}
entries=json.loads((raw/'manifest.json').read_text(encoding='utf-8'));prior={e['key']:e for e in entries}
source=['/* Generated by tools/weather_art_assets.py; sources: assets/weather-soft3d/. */','#include "resource_store.h"','#include "resource_manifest.h"','#include "weather_art.h"','#if LV_COLOR_DEPTH != 16 || LV_COLOR_16_SWAP','#error "Weather artwork requires native RGB565 little-endian"','#endif']
checks=[]
for i,name in enumerate(names):
 image=rain if i in new_cells else base;cell=new_cells.get(i,i);rows=2 if i in new_cells else 3;col,row=cell%4,cell//4
 crop=image.crop((round(col*image.width/4),round(row*image.height/rows),round((col+1)*image.width/4),round((row+1)*image.height/rows)))
 for size in (196,56):
  icon=Image.new('RGBA',(size,size));icon.alpha_composite(crop.resize((size-4,size-4),Image.Resampling.LANCZOS),(2,2));icon.save(assets/f'{name}-{size}.png')
  data=bytearray()
  for r,g,b,a in icon.getdata():
   rgb=((r>>3)<<11)|((g>>2)<<5)|(b>>3);data.extend((rgb&255,rgb>>8,a))
  key=f'weather_art__weather_art_{i}_{size}_pixels';filename=key+'.bin';(raw/filename).write_bytes(data)
  entry={'key':key,'file':filename,'size':len(data),'sha256':hashlib.sha256(data).hexdigest()}
  if key in prior:prior[key].update(entry)
  else:entries.append(entry)
  source.append(f'static lv_img_dsc_t weather_art_{i}_{size}={{.header={{.cf=LV_IMG_CF_TRUE_COLOR_ALPHA,.always_zero=0,.w={size},.h={size}}},.data_size={len(data)},.data=NULL}};')
  checks.append((name,size,icon.getchannel('A').getextrema()))
for size in (196,56):source.append(f'const lv_img_dsc_t *const weather_art_{size}[WEATHER_ART_COUNT]={{'+','.join(f'&weather_art_{i}_{size}' for i in range(len(names)))+'};')
source.append('bool weather_art_bind_resources(void) {')
for i in range(len(names)):
 for size in (196,56):
  macro=f'RESOURCE_WEATHER_ART__WEATHER_ART_{i}_{size}_PIXELS';source.append(f' weather_art_{i}_{size}.data=resource_store_data({macro}_OFFSET,{macro}_SIZE);if(!weather_art_{i}_{size}.data)return false;')
source.append(' return true;\n}')
(ROOT/'main/apps/weather/weather_art.c').write_text('\n'.join(source)+'\n',encoding='utf-8')
(ROOT/'main/apps/weather/weather_art.h').write_text('#pragma once\n#include "lvgl.h"\n#define WEATHER_ART_COUNT 16\nextern const lv_img_dsc_t *const weather_art_196[WEATHER_ART_COUNT];\nextern const lv_img_dsc_t *const weather_art_56[WEATHER_ART_COUNT];\n',encoding='utf-8')
(raw/'manifest.json').write_text(json.dumps(entries,indent=2)+'\n',encoding='utf-8')
assert all(alpha==(0,255) for _,_,alpha in checks)
print('Encoded 16 icons at 196px/56px; alpha preserved; original non-rain resources retained')
